public class Cat {

  private String breed;
  private int age;

  /*
   * Constructor for the Cat class
   * Stores the breed and age
   */
  public Cat(String breed, int age) {
    this.breed = breed;
    this.age = age;
  }

  // Returns the breed of the cat
  public String getBreed() {
    return breed;
  }

  // Returns the age of the cat
  public int getAge() {
    return age;
  }
}


